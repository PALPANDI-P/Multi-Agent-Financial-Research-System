"""The error envelope of the HTTP API.

Every non 2xx response of the API has the same shape::

    {
      "error": {
        "code": "not_found",
        "message": "the workspace ... does not exist",
        "details": {"workspace_id": "..."},
        "request_id": "0f1e..."
      }
    }

``code``
    A stable, machine readable string.  The domain exceptions carry their
    own code, therefore the code of an error never changes between
    releases.
``message``
    A human readable description.  It may change at any time.
``details``
    JSON serialisable diagnostic context.  It never carries a secret and
    never carries an internal path.
``request_id``
    The id of the request, taken from the ``X-Request-ID`` header or
    generated by the request id middleware.  It is the same id that is
    written into the log records of the request, therefore a user can
    report it and the operator can find the request in the log.

Security rules
--------------
* An unexpected exception never reaches the client: the response carries a
  **generic** message, the stack trace and the text of the exception stay
  in the log.
* No response ever carries a credential, a connection string or an
  internal file system path.
"""

from __future__ import annotations

from typing import Any

from fastapi import FastAPI, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from starlette.exceptions import HTTPException as StarletteHTTPException

from app.core.exceptions import AppError
from app.core.logging import clear_context, current_request_id, get_logger

__all__ = [
    "GENERIC_INTERNAL_MESSAGE",
    "PayloadTooLargeError",
    "error_response",
    "register_exception_handlers",
]

logger = get_logger(__name__)

#: The message of an unexpected error.  It is deliberately generic: the
#: details of the failure belong into the log, not into the response.
GENERIC_INTERNAL_MESSAGE = "An unexpected error occurred."

#: The code of a request that exceeds the maximum body size.
PAYLOAD_TOO_LARGE_CODE = "payload_too_large"

#: The code of a request that does not satisfy the request schema.
REQUEST_VALIDATION_ERROR_CODE = "request_validation_error"

#: The code of an error that was raised by the framework itself.
HTTP_ERROR_CODE = "http_error"

#: The code of an unexpected error.
INTERNAL_ERROR_CODE = "internal_error"


class PayloadTooLargeError(AppError):
    """Raised when a request body exceeds the configured maximum size."""

    default_code = PAYLOAD_TOO_LARGE_CODE
    default_http_status = 413


def error_response(
    code: str,
    message: str,
    *,
    status_code: int,
    details: dict[str, Any] | None = None,
    request_id: str | None = None,
) -> JSONResponse:
    """Return the standard error envelope as a JSON response.

    Parameters
    ----------
    code:
        The stable, machine readable code of the error.
    message:
        The human readable description of the error.
    status_code:
        The HTTP status code of the response.
    details:
        Optional JSON serialisable diagnostic context.
    request_id:
        The id of the request.  When it is omitted the id of the current
        logging context is used.
    """
    resolved_request_id = request_id if request_id is not None else current_request_id()
    return JSONResponse(
        status_code=status_code,
        content={
            "error": {
                "code": code,
                "message": message,
                "details": dict(details or {}),
                "request_id": resolved_request_id,
            }
        },
    )


def _request_id_of(request: Request) -> str | None:
    """Return the id of the request.

    The id is taken from the scope (the request id middleware writes it
    there, and the scope is shared by every layer of the stack) and falls
    back to the logging context.  The fallback is needed for the errors
    that are handled *outside* of the request id middleware.
    """
    scope_id = request.scope.get("request_id")
    if isinstance(scope_id, str) and scope_id:
        return scope_id
    return current_request_id()


def _jsonable(value: Any) -> Any:
    """Return *value* as a JSON serialisable structure.

    Everything that is not a JSON primitive is converted to its string
    representation, therefore a value that cannot be serialised (a file
    object for example) can never break the response.
    """
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, dict):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (list, tuple, set, frozenset)):
        return [_jsonable(item) for item in value]
    return str(value)


async def _handle_app_error(request: Request, exc: Exception) -> JSONResponse:
    """Translate a domain error into the error envelope."""
    assert isinstance(exc, AppError)
    details = dict(exc.details)
    if exc.error_code is not None:
        details.setdefault("error_code", exc.error_code)
    return error_response(
        exc.code,
        exc.message,
        status_code=exc.http_status,
        details=details,
        request_id=_request_id_of(request),
    )


async def _handle_request_validation_error(
    request: Request,
    exc: Exception,
) -> JSONResponse:
    """Translate a request validation error into the error envelope."""
    assert isinstance(exc, RequestValidationError)
    return error_response(
        REQUEST_VALIDATION_ERROR_CODE,
        "the request does not satisfy the expected schema",
        status_code=422,
        details={"errors": _jsonable(exc.errors())},
        request_id=_request_id_of(request),
    )


async def _handle_http_exception(request: Request, exc: Exception) -> JSONResponse:
    """Translate an error of the framework into the error envelope."""
    assert isinstance(exc, StarletteHTTPException)
    detail = exc.detail
    if isinstance(detail, str):
        message = detail
        details: dict[str, Any] = {}
    else:
        message = "the request could not be processed"
        details = {"detail": _jsonable(detail)}
    return error_response(
        HTTP_ERROR_CODE,
        message,
        status_code=exc.status_code,
        details=details,
        request_id=_request_id_of(request),
    )


async def _handle_unexpected_error(request: Request, exc: Exception) -> JSONResponse:
    """Translate an unexpected error into a generic error envelope.

    The real error is written into the log - with its stack trace - and
    **nothing** of it reaches the client.
    """
    request_id = _request_id_of(request)
    try:
        logger.exception(
            "unhandled error while handling %s %s",
            request.method,
            request.url.path,
        )
    finally:
        # The request id middleware keeps the context bound while the
        # exception travels up the stack; it is cleared here, because this
        # handler runs outside of that middleware.
        clear_context()
    response = error_response(
        INTERNAL_ERROR_CODE,
        GENERIC_INTERNAL_MESSAGE,
        status_code=500,
        details={},
        request_id=request_id,
    )
    if request_id:
        # The response is created outside of the request id middleware,
        # therefore the header is set here.
        response.headers["X-Request-ID"] = request_id
    return response


def register_exception_handlers(app: FastAPI) -> None:
    """Register the exception handlers of the API on *app*."""
    app.add_exception_handler(AppError, _handle_app_error)
    app.add_exception_handler(RequestValidationError, _handle_request_validation_error)
    app.add_exception_handler(StarletteHTTPException, _handle_http_exception)
    app.add_exception_handler(Exception, _handle_unexpected_error)