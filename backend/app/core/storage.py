"""Replaceable storage backend for uploaded documents.

The ingestion pipeline must never touch the file system directly: it asks a
:class:`StorageBackend` for a key, writes the bytes and later reads them back.
The abstraction exists so that a future S3 / Azure Blob / ADLS backend can be
plugged in without touching a single line of the pipeline.

Only the local file system backend is implemented today.  :func:`create_storage_backend`
is the documented seam for the others.

Security
--------
The local backend is the trust boundary between untrusted uploads and the
file system, therefore it defends itself:

* The key returned by :meth:`LocalStorage.save` is generated by the backend
  (``YYYY/MM/<uuid4>.<ext>``).  The caller's filename is **never** part of
  the path, so a hostile name such as ``../../etc/passwd`` cannot influence
  where the bytes land.
* :meth:`LocalStorage.path_for` resolves the requested key and asserts that
  the result stays inside the storage root.  Anything that escapes (``..``,
  an absolute path, a Windows drive letter, a UNC path) is rejected with
  :class:`~app.core.exceptions.StorageError` and the code
  ``storage_path_escape``.
* Writes are atomic: the bytes are written to a temporary file in the target
  directory and then moved into place with :func:`os.replace`.
"""

from __future__ import annotations

import os
import re
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Protocol, runtime_checkable

from app.core.config import Settings
from app.core.exceptions import ConfigurationError, StorageError

__all__ = [
    "MAX_EXTENSION_LENGTH",
    "LocalStorage",
    "StorageBackend",
    "create_storage_backend",
    "normalise_extension",
]

#: Maximum length of a file extension, dots included.
MAX_EXTENSION_LENGTH: int = 16

#: Extensions may only use these characters.
_EXTENSION_PATTERN = re.compile(
    rf"^[A-Za-z0-9._-]{{1,{MAX_EXTENSION_LENGTH}}}$"
)

#: A Windows drive letter such as ``C:`` at the start of a key.
_DRIVE_PATTERN = re.compile(r"^[A-Za-z]:")


@runtime_checkable
class StorageBackend(Protocol):
    """The storage contract used by the ingestion pipeline."""

    def save(self, data: bytes, *, extension: str) -> str:
        """Store *data* and return the storage key it was written to."""
        ...

    def read(self, storage_key: str) -> bytes:
        """Return the bytes stored under *storage_key*."""
        ...

    def delete(self, storage_key: str) -> None:
        """Delete *storage_key*; deleting a missing object is not an error."""
        ...

    def exists(self, storage_key: str) -> bool:
        """Return whether *storage_key* refers to a stored object."""
        ...

    def path_for(self, storage_key: str) -> Path:
        """Return the local path of *storage_key*."""
        ...


def normalise_extension(extension: str) -> str:
    """Return the canonical form of *extension*.

    The extension is lowercased and prefixed with a single dot.  Only the
    characters ``A-Z``, ``a-z``, ``0-9``, ``.``, ``_`` and ``-`` are allowed
    and the result is at most :data:`MAX_EXTENSION_LENGTH` characters long.
    Anything else is rejected with :class:`~app.core.exceptions.StorageError`
    (code ``invalid_extension``).
    """
    if not isinstance(extension, str):
        raise StorageError(
            "file extension must be a string",
            code="invalid_extension",
            details={"extension": str(extension)},
        )
    candidate = extension.strip()
    if not candidate:
        raise StorageError(
            "file extension must not be empty",
            code="invalid_extension",
        )
    if not _EXTENSION_PATTERN.match(candidate):
        raise StorageError(
            "file extension contains unsupported characters",
            code="invalid_extension",
            details={"extension": extension, "max_length": MAX_EXTENSION_LENGTH},
        )
    normalised = candidate.lower()
    if set(normalised) <= {"."}:
        raise StorageError(
            "file extension must contain at least one non-dot character",
            code="invalid_extension",
            details={"extension": extension},
        )
    if not normalised.startswith("."):
        normalised = f".{normalised}"
    return normalised


class LocalStorage:
    """A :class:`StorageBackend` that stores documents on the local file system."""

    def __init__(self, root: Path) -> None:
        """Create a backend that stores objects below *root*."""
        self.root = Path(root)

    # ------------------------------------------------------------------
    # helpers
    # ------------------------------------------------------------------
    def _resolved_root(self) -> Path:
        """Return the absolute, symlink resolved storage root."""
        return self.root.resolve()

    def path_for(self, storage_key: str) -> Path:
        """Return the absolute path of *storage_key*.

        The key is resolved and the result is asserted to live inside the
        storage root.  Every attempt to escape the root (``..`` segments, an
        absolute path, a Windows drive letter or a UNC path) raises
        :class:`~app.core.exceptions.StorageError` with the code
        ``storage_path_escape``.
        """
        if not isinstance(storage_key, str) or not storage_key.strip():
            raise StorageError(
                "storage key must be a non-empty string",
                code="storage_path_escape",
                details={"storage_key": str(storage_key)},
            )
        if "\\" in storage_key:
            raise StorageError(
                "storage key must not contain backslashes",
                code="storage_path_escape",
                details={"storage_key": storage_key},
            )
        if _DRIVE_PATTERN.match(storage_key):
            raise StorageError(
                "storage key must not contain a drive letter",
                code="storage_path_escape",
                details={"storage_key": storage_key},
            )
        if storage_key.startswith("/"):
            raise StorageError(
                "storage key must not be an absolute path",
                code="storage_path_escape",
                details={"storage_key": storage_key},
            )

        candidate = Path(storage_key)
        if candidate.is_absolute() or candidate.drive or candidate.root or candidate.anchor:
            raise StorageError(
                "storage key must be a relative path inside the storage root",
                code="storage_path_escape",
                details={"storage_key": storage_key},
            )
        if ".." in candidate.parts:
            raise StorageError(
                "storage key must not contain parent directory segments",
                code="storage_path_escape",
                details={"storage_key": storage_key},
            )

        root = self._resolved_root()
        target = (root / candidate).resolve()
        if target == root or root not in target.parents:
            raise StorageError(
                "storage key escapes the storage root",
                code="storage_path_escape",
                details={"storage_key": storage_key},
            )
        return target

    # ------------------------------------------------------------------
    # StorageBackend protocol
    # ------------------------------------------------------------------
    def save(self, data: bytes, *, extension: str) -> str:
        """Store *data* and return the key it was written to.

        The key is ``YYYY/MM/<uuid4>.<ext>``: it carries no information from
        the caller's filename and is therefore safe by construction.
        """
        if not isinstance(data, (bytes, bytearray, memoryview)):
            raise StorageError(
                "document payload must be bytes",
                code="invalid_payload",
                details={"type": type(data).__name__},
            )
        suffix = normalise_extension(extension)

        now = datetime.now(UTC)
        key = f"{now:%Y}/{now:%m}/{uuid.uuid4().hex}{suffix}"
        target = self.path_for(key)
        target.parent.mkdir(parents=True, exist_ok=True)

        temporary = target.parent / f".{target.name}.{uuid.uuid4().hex}.tmp"
        try:
            with open(temporary, "wb") as handle:
                handle.write(bytes(data))
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, target)
        except OSError as exc:
            temporary.unlink(missing_ok=True)
            raise StorageError(
                "could not write the document to storage",
                code="storage_write_failed",
                details={"storage_key": key},
            ) from exc
        return key

    def read(self, storage_key: str) -> bytes:
        """Return the bytes stored under *storage_key*."""
        target = self.path_for(storage_key)
        try:
            return target.read_bytes()
        except FileNotFoundError as exc:
            raise StorageError(
                "the requested document does not exist in storage",
                code="storage_not_found",
                details={"storage_key": storage_key},
            ) from exc
        except OSError as exc:
            raise StorageError(
                "could not read the document from storage",
                code="storage_read_failed",
                details={"storage_key": storage_key},
            ) from exc

    def delete(self, storage_key: str) -> None:
        """Delete *storage_key*; a missing document is not an error."""
        target = self.path_for(storage_key)
        try:
            target.unlink()
        except FileNotFoundError:
            return
        except OSError as exc:
            raise StorageError(
                "could not delete the document from storage",
                code="storage_delete_failed",
                details={"storage_key": storage_key},
            ) from exc

    def exists(self, storage_key: str) -> bool:
        """Return whether *storage_key* refers to a stored document."""
        return self.path_for(storage_key).is_file()


def create_storage_backend(settings: Settings) -> StorageBackend:
    """Return the storage backend selected by *settings*.

    ``local`` is the only provider that is implemented today.  Any other
    provider raises :class:`~app.core.exceptions.ConfigurationError`: this is
    the documented seam where an S3 / ADLS backend will be plugged in.
    """
    provider = str(getattr(settings, "storage_provider", "") or "").strip().lower()
    if provider == "local":
        return LocalStorage(settings.storage_root)
    raise ConfigurationError(
        f"unsupported storage provider {provider!r}; only 'local' is implemented",
        code="unsupported_storage_provider",
        details={"storage_provider": provider},
    )
